// Chuỗi giao diện. t('key', {param}) → chuỗi theo ngôn ngữ hiện tại (vi mặc định, en dự phòng về vi).
let lang = 'vi';
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'vi';
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lang;
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('app.metaDesc'));
}
export function getLang() { return lang; }
export function t(key, params) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.vi[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
  return s;
}
